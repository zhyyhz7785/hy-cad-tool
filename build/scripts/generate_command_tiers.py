#!/usr/bin/env python3
"""从 src/ReCall/commands.json 生成编译期许可档位表 CommandTiers.g.cs。"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
JSON_PATH = REPO / "src" / "ReCall" / "commands.json"
OUT_PATH = REPO / "src" / "HyCADTool" / "Shell" / "Licensing" / "CommandTiers.g.cs"


def normalize_tier(raw: object) -> str:
    if raw is None:
        return "standard"
    text = str(raw).strip()
    if not text:
        return "standard"
    lower = text.lower()
    if lower in ("freemium", "free"):
        return "freemium"
    if lower == "standard":
        return "standard"
    if lower in ("professional", "pro"):
        return "professional"
    if lower in ("enterprise", "ent"):
        return "enterprise"
    return "standard"


def load_tiers() -> list[tuple[str, str]]:
    root = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    commands = root.get("commands") or {}
    rows: list[tuple[str, str]] = []
    for key, value in commands.items():
        if value is None or not isinstance(value, dict):
            continue
        rows.append((key, normalize_tier(value.get("tier"))))
    rows.sort(key=lambda item: item[0].casefold())
    return rows


def csharp_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def render(rows: list[tuple[str, str]]) -> str:
    lines = [
        "// <auto-generated />",
        "// 由 build/scripts/generate_command_tiers.py 从 src/ReCall/commands.json 生成，不要手改。",
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace HyCADTool.Shell.Licensing",
        "{",
        "    /// <summary>",
        "    /// 命令许可档位编译期常量表。授权判断只读本表，不读运行时 commands.json 的 tier。",
        "    /// </summary>",
        "    public static class CommandTiers",
        "    {",
        "        public static readonly IReadOnlyDictionary<string, string> Table =",
        "            new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)",
        "            {",
    ]
    for key, tier in rows:
        lines.append(f'                {{ "{csharp_string(key)}", "{tier}" }},')
    lines.extend(
        [
            "            };",
            "",
            "        public static string GetRaw(string key)",
            "        {",
            "            if (string.IsNullOrWhiteSpace(key))",
            "                return null;",
            "            string value;",
            "            return Table.TryGetValue(key.Trim(), out value) ? value : null;",
            "        }",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    if not JSON_PATH.is_file():
        print(f"找不到 {JSON_PATH}", file=sys.stderr)
        return 1
    text = render(load_tiers())
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(text, encoding="utf-8")
    print(f"已写入 {OUT_PATH.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
