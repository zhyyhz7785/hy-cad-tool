    /// <summary>
    /// P1??????? AutoCAD ???? ??? ????????? ??? ???? / ??? Domain Alignment ??? ??? Xdata ??? ??????????
    ///
    /// ?????v1.2.1 ?????????????????
    /// - ???????????"???????????????????????????????"??
    /// - ? <see cref="Editor.GetSelection"/> + LWPOLYLINE ??????????????????????Ctrl ???????
    /// - ??????? 2D <c>Polyline</c>??<c>Polyline3d</c> / <c>Line</c> ??? P1 ????????????P3 ???????????
    /// - ESC / ?????????????????????????????????
    /// - ??????????????? ??? ???????????? Alignment ??? Centerline???? Xdata ???? GUID ??????????
    ///
    /// ????????
    /// - ????????????"????"??????????? Transaction ??????????????
    /// - ??? Polyline ????????????????????????????? rebind / BlockTable ????????????
    /// - ??????? + Xdata ??? <see cref="RoadAlignmentService.ImportFromPolyline"/> ???????
    /// - JSON ???????? v1.1 ????????????????????? <see cref="RoadJsonExportService.SaveForDocument"/>???????? Timer??
    ///   ?????????? JSON ???????????????? polyline ????????????? I/O ?????????
    ///
    /// v1.2 ?????????????????????????????
    /// - ????????????????????????????
    /// - ?????????"????????? / ????????? Alignment"??? <see cref="Alignment.Validate"/> + bulge ???????
    /// - ???**??????**????????????????????????????????????????????????
    /// - ???**?????**???????????????????????????????????????Y/N????
    ///   ?????????????**???????????? Alignment**?????????????????????????????
    /// - ??????????? / ??????? 0 / Elements ????????? / ?????? bulge = 0 ????? Arc ???????????????????
    /// - ????????????????????????????????????????????????????????????? <c>hyRoadAw</c>??<c>rlaw</c>?????
    /// </summary>
    public sealed class RoadAlignmentCommand
    {
        /// <summary>
        /// ??? Polyline ?????????????????????????????? / ?????????????????
        /// </summary>
        private sealed class ImportOutcome
        {
            public Alignment Alignment;
            public int RawBulgeNonZeroCount;
            public bool RawHasSegmentArcs;
            public bool RawHasSegmentLines;
            public bool WasNew;
            public readonly List<string> Violations = new List<string>();
            public readonly List<string> Advisories = new List<string>();
        }

        public void Execute()
        {
            var doc = AcApp.DocumentManager.MdiActiveDocument;
            if (doc == null) return;

            var ed = doc.Editor;
            var db = doc.Database;

            // ??????????????LWPOLYLINE ??????????????????? AddAllowedClass(typeof(Polyline), exactMatch:true)
            var pso = new PromptSelectionOptions
            {
                MessageForAdding = "\n[???] ??????????????????????????????????????????????",
                AllowDuplicates = false,
            };
            var filter = new SelectionFilter(new[] { new TypedValue((int)DxfCode.Start, "LWPOLYLINE") });

            var psr = ed.GetSelection(pso, filter);
            if (psr.Status != PromptStatus.OK || psr.Value == null || psr.Value.Count == 0)
            {
                ed.WriteMessage("\n[???] ????????");
                return;
            }

            var svc = ServiceLocator.Resolve<RoadAlignmentService>();
            var exporter = ServiceLocator.Resolve<RoadJsonExportService>();
            var registry = ServiceLocator.Resolve<RoadDesignRegistry>();

            var outcomes = new List<ImportOutcome>();
            int skippedNotPolyline = 0;
            int skippedImportFailed = 0;

            using (doc.LockDocument())
            using (var tr = db.TransactionManager.StartTransaction())
            {
                // ??? rebind ?????????? SAVEAS ??? doc.Name ??????????????Registry ?????? design ??????????? key??
                // ? rebind ???? ImportFromPolyline ??? GetOrCreate ?????? key ???????Xdata GUID ????????????? Alignment??
                // ???????? polyline ???????"??? Alignment"??????? design????? key ??????????????? JSON ???????
                // ??????????????? rebind ????????????????????????????
                svc.RebindForDocument(doc.Name, tr, db);

                foreach (SelectedObject so in psr.Value)
                {
                    if (so == null) continue;

                    DBObject picked;
                    try { picked = tr.GetObject(so.ObjectId, OpenMode.ForRead); }
                    catch { skippedImportFailed++; continue; }

                    if (!(picked is Polyline poly))
                    {
                        // SelectionFilter("LWPOLYLINE") ????????????????????????????????SDK ??????????????????
                        skippedNotPolyline++;
                        continue;
                    }

                    var outcome = new ImportOutcome();

                    // ?????? bulge ?????????????????? AutoCAD??????"DWG ??????????????"?????
                    // ?????????? bulge==0 ?????????????????PEDIT ??? S??Spline??????? ?????? ???????????????????????????????
                    // bulge ????? 0??Polyline3D.ShouldSerializeBulges ????????? JSON ??????
                    // GetSegmentType ???????? Line / Arc / Coincident / Point / Empty ?????
                    // ?????????????????? Line???? Arc / ?????????????? V2 ??????????????????"?????????????????"????????????
                    for (int i = 0; i < poly.NumberOfVertices; i++)
                    {
                        var segType = poly.GetSegmentType(i);
                        if (segType == SegmentType.Arc) outcome.RawHasSegmentArcs = true;
                        else if (segType == SegmentType.Line) outcome.RawHasSegmentLines = true;
                        if (Math.Abs(poly.GetBulgeAt(i)) > 1e-12) outcome.RawBulgeNonZeroCount++;
                    }

                    try
                    {
                        // Xdata ?????????? ForWrite
                        poly.UpgradeOpen();
                        outcome.Alignment = svc.ImportFromPolyline(doc.Name, tr, db, poly, out outcome.WasNew);
                    }
                    catch (Exception ex)
                    {
                        ed.WriteMessage($"\n[???] ???? Handle={so.ObjectId.Handle} ????{ex.Message}");
                        skippedImportFailed++;
                        continue;
                    }

                    if (outcome.Alignment == null)
                    {
                        skippedImportFailed++;
                        continue;
                    }

                    // ?? hyRoadAlnByPi ???????????????????????? hy-settings ???
                    if (outcome.WasNew)
                    {
                        var defaults = SettingsPanelViewModel.Current?.CreateAlignmentDefaults();
                        if (defaults != null)
                            outcome.Alignment.StartStation = defaults.DefaultStartStation;
                    }

                    outcomes.Add(outcome);
                }

                tr.Commit();
            }

            if (outcomes.Count == 0)
            {
                ed.WriteMessage(
                    $"\n[???] ???????????????????????? {psr.Value.Count} ???"
                    + $"?? Polyline {skippedNotPolyline} ????????? {skippedImportFailed} ??????");
                return;
            }

            // ?????????????????v1.1 ???????????????????????????????
            // ???????????? JSON ???????????????? polyline ????????????????????? / ???????????
            string savedTo = null;
            if (registry.TryGet(doc.Name, out var design))
            {
                savedTo = exporter.SaveForDocument(design, doc.Name);
            }

            // ??????? Validate + bulge ??????????????????????????????????
            int newCount = 0, updatedCount = 0;
            foreach (var o in outcomes)
            {
                if (o.WasNew) newCount++; else updatedCount++;

                ed.WriteMessage(
                    $"\n[???] [{(o.WasNew ? "+" : "~")}] {o.Alignment.Name}??"
                    + $"Id={o.Alignment.Id:N}?????? {o.Alignment.Centerline.VertexCount} ???"
                    + $"??? {o.RawBulgeNonZeroCount} ???"
                    + $"?????? {o.Alignment.Centerline.GetPlanarLength():F3} m???");

                // (V1) Alignment ???????????????????? / ?????? / Elements ?????
                var validation = o.Alignment.Validate();
                if (!validation.Ok)
                {
                    foreach (var e in validation.Errors) o.Violations.Add(e);
                }

                // (V2) ??????????? bulge ??? 0??????????? PEDIT ??? S ?????????Centerline ??????????????
                // ?????????????????????? SegmentType.Line ????????????????????????????????????? 1 ??????????????
                // ????"?????? Arc ???????? Line ?????????????? Empty/Point/Coincident??"????????????????????????????
                if (o.RawBulgeNonZeroCount == 0
                    && !o.RawHasSegmentArcs
                    && !o.RawHasSegmentLines
                    && o.Alignment.Centerline.VertexCount >= 2)
                {
                    o.Violations.Add(
                        "???????????????/????????????? bulge=0 ??????????????????????????????????????? PEDIT ??? S ??????????"
                        + " ????PEDIT ??? D ????????? ??? PEDIT ??? F ????????? ??? ????? hyRoadA???????? hyRoadAlnByPi ? PI ?????");
                }

                // (A1) ????????? PI ???????????????????????? hyRoadAlnEditPi / InsertPi / DeletePi ?????
                if (o.Alignment.Centerline.HasArcs
                    && (o.Alignment.Source == null
                        || o.Alignment.Source.PiElements == null
                        || o.Alignment.Source.PiElements.Count < 2))
                {
                    o.Advisories.Add(
                        "??????????????bulge???0??????????????????? PI ????"
                        + " ???????? PI ????????????????????? hyRoadAlnByPi?????????????? / ???? / ?? / ??????????");
                }
            }

            ed.WriteMessage(
                $"\n[??] ??????? {newCount} ???? {updatedCount} ?"
                + (skippedNotPolyline + skippedImportFailed > 0
                    ? $"??? {skippedNotPolyline + skippedImportFailed} ?"
                    : string.Empty)
                + "?");

            if (savedTo != null)
                ed.WriteMessage($"\n[???] JSON ??????????{savedTo}");
            else
                ed.WriteMessage("\n[???] ?????????DWG ??????????? RoadDesign ????????????? DWG ????????? hyRoadSave ?????");

            // ???? advisories???????????
            foreach (var o in outcomes)
            {
                foreach (var a in o.Advisories)
                    ed.WriteMessage($"\n[???] ????{o.Alignment.Name}????{a}");
            }

            // ?????????????????????????????????????????????
            int totalViolations = 0;
            ImportOutcome firstBad = null;
            foreach (var o in outcomes)
            {
                if (o.Violations.Count == 0) continue;
                if (firstBad == null) firstBad = o;
                totalViolations += o.Violations.Count;
                ed.WriteMessage($"\n[???] ??? {o.Alignment.Name} ??????? {o.Violations.Count} ?????????");
                foreach (var v in o.Violations) ed.WriteMessage("\n  � " + v);
            }

            if (firstBad == null)
            {
                // ?????????????????????????????????????????????????? hyRoadAw??rlaw?????
                return;
            }

            // ???????????????????????????????????????
            var kw = new PromptKeywordOptions(
                $"\n[???] ??? {totalViolations} ???????????????????????????????????? {firstBad.Alignment.Name}????[???(Y)/?(N)] <???>??")
            {
                AllowNone = true,
            };
            kw.Keywords.Add("Y");
            kw.Keywords.Add("N");
            kw.Keywords.Default = "Y";
            var kwRes = ed.GetKeywords(kw);
            bool openWb =
                kwRes.Status == PromptStatus.None
                || (kwRes.Status == PromptStatus.OK && kwRes.StringResult == "Y");

            if (!openWb)
            {
                ed.WriteMessage("\n[???] ???????????????? hyRoadAw??rlaw????????????????????");
                return;
            }

            try
            {
                var panels = ServiceLocator.Resolve<PanelManager>();
                panels?.ShowAlignmentWorkbench(firstBad.Alignment.Id, piIndex: null);
            }
            catch
            {
                // ??????????????? / WPF ?????????????????????????????
            }
        }
    }
}
